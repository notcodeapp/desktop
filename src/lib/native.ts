export const nativeAvailable = Boolean(window.__TAURI_INTERNALS__);
export const event = <T>(name: string, handler: (payload: T) => void) => nativeAvailable ? listen<T>(name, e => handler(e.payload)) : Promise.resolve(() => {});
const call = <T>(command: string, args?: Record<string, unknown>) => invoke<T>(command, args);

